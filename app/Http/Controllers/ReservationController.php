     * Store a newly created resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @return \Illuminate\Http\Response
     */
    public function store(Request $request)
    {
        $res = new Reservation;
		
		$res->person_capacity = $request->input('dish_recipe');
		$res->strtime = $request->input('dish_category');
		$res->endtime = $request->input('dish_rating');
		$res->reserveday = $request->input('dish_details');
		$res->customer_notes = $request->input('dish_details');
		
		$res->save();
		
		return redirect('superadmin/reserveadd');
    }

